import { useEffect, type ReactNode } from 'react';
import { X } from 'lucide-react';
import type { EventSource, TaskStatus } from '../../../shared/types';
import { sourceLabel, useStore } from '../store';

const sourceStyle: Record<EventSource, string> = {
  real: 'bg-emerald-600 text-white',
  simulated: 'bg-violet-600 text-white',
  replayed: 'bg-blue-600 text-white',
  unknown: 'bg-stone-500 text-white',
};
const sourceHelp: Record<EventSource, string> = {
  real: 'From an authorised local source that explicitly labelled it real.',
  simulated: 'Fictional activity generated by the simulation provider.',
  replayed: 'Historical events being played back.',
  unknown: 'From a local file without a trustworthy real/simulated label.',
};

export function SourceBadge({ source, original }: { source: EventSource; original?: string }) {
  return (
    <span
      className={`chip ${sourceStyle[source]}`}
      title={sourceHelp[source] + (original ? ` Originally ${original}.` : '')}
    >
      {sourceLabel[source]}
      {original && <span className="opacity-80">· {String(original).toUpperCase()}</span>}
    </span>
  );
}

const statusStyle: Record<TaskStatus, [string, string]> = {
  pending: ['bg-stone-200 text-stone-800', '⏳'],
  active: ['bg-amber-200 text-amber-900', '⚙️'],
  completed: ['bg-emerald-200 text-emerald-900', '✓'],
  failed: ['bg-rose-200 text-rose-900', '✕'],
};
export function StatusChip({ status }: { status: TaskStatus }) {
  const [cls, icon] = statusStyle[status];
  return (
    <span className={`chip ${cls}`}>
      {icon} {status}
    </span>
  );
}

export function Progress({ value }: { value: number | null | undefined }) {
  if (value == null)
    return (
      <span
        className="indeterminate relative inline-block h-2 w-full min-w-12 overflow-hidden rounded bg-stone-200"
        title="Progress not reported by the source"
        aria-label="Progress unknown"
      />
    );
  return (
    <span
      className="relative inline-block h-2 w-full min-w-12 overflow-hidden rounded bg-stone-200"
      aria-label={`${Math.round(value * 100)}%`}
    >
      <span
        className="absolute inset-y-0 left-0 rounded bg-emerald-500"
        style={{ width: `${Math.round(value * 100)}%` }}
      />
    </span>
  );
}

export function Modal({
  title,
  children,
  wide,
  onClose,
}: {
  title: string;
  children: ReactNode;
  wide?: boolean;
  onClose?: () => void;
}) {
  const close = onClose ?? (() => useStore.getState().openModal(null));
  useEffect(() => {
    const key = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        e.stopPropagation();
        close();
      }
    };
    window.addEventListener('keydown', key, true);
    return () => window.removeEventListener('keydown', key, true);
  });
  return (
    <div
      className="absolute inset-0 z-40 flex items-center justify-center bg-ink/40 p-2 sm:p-4"
      onPointerDown={(e) => e.target === e.currentTarget && close()}
      role="dialog"
      aria-label={title}
    >
      <div
        className={`panel flex max-h-[94%] w-full flex-col sm:max-h-[88vh] ${wide ? 'max-w-5xl' : 'max-w-xl'}`}
      >
        <div className="flex items-center justify-between border-b-2 border-ink/80 bg-paper px-3 py-2">
          <h2 className="text-sm font-extrabold">{title}</h2>
          <button className="btn !px-1.5" onClick={close} aria-label="Close">
            <X size={14} />
          </button>
        </div>
        <div className="scroll-thin overflow-auto p-3">{children}</div>
      </div>
    </div>
  );
}

export function Section({
  title,
  children,
  right,
}: {
  title: string;
  children: ReactNode;
  right?: ReactNode;
}) {
  return (
    <section className="mb-3">
      <div className="mb-1 flex items-center justify-between">
        <h3 className="panel-title">{title}</h3>
        {right}
      </div>
      {children}
    </section>
  );
}

export const fmtTime = (iso?: string) =>
  iso
    ? new Date(iso).toLocaleTimeString([], {
        hour: '2-digit',
        minute: '2-digit',
        second: '2-digit',
      })
    : '—';
export const fmtDateTime = (iso?: string | number) =>
  iso
    ? new Date(iso).toLocaleString([], {
        month: 'short',
        day: 'numeric',
        hour: '2-digit',
        minute: '2-digit',
      })
    : '—';
export function fmtDuration(ms: number | null) {
  if (ms == null) return '—';
  const s = Math.round(ms / 1000);
  if (s < 60) return `${s}s`;
  const m = Math.floor(s / 60);
  if (m < 60) return `${m}m ${s % 60}s`;
  return `${Math.floor(m / 60)}h ${m % 60}m`;
}
export const ago = (iso?: string) => {
  if (!iso) return 'never';
  const s = Math.max(0, Math.round((Date.now() - Date.parse(iso)) / 1000));
  return s < 60
    ? `${s}s ago`
    : s < 3600
      ? `${Math.floor(s / 60)}m ago`
      : `${Math.floor(s / 3600)}h ago`;
};
